// Effect spec: code + sign + level letter, e.g. "ДС+h", "КМ-l".
type opt struct {
	text string
	effs []string
}

type question struct {
	text, typ string
	opts      []opt
}

type assessment struct {
	title, desc string
	ageDays     int // created this many days before now
	qs          []question
}

func o(text string, effs ...string) opt { return opt{text, effs} }

func single(text string, opts ...opt) question   { return question{text, "single", opts} }
func multiple(text string, opts ...opt) question { return question{text, "multiple", opts} }

// rating builds a 5-point agreement scale; "-" before a code reverses its direction.
func rating(text string, codes ...string) question {
	labels := []string{"1 — совершенно не согласен", "2 — скорее не согласен", "3 — затрудняюсь ответить", "4 — скорее согласен", "5 — полностью согласен"}
	effs := [][2]string{{"-", "m"}, {"-", "l"}, {"", ""}, {"+", "m"}, {"+", "h"}}
	flip := map[string]string{"+": "-", "-": "+"}
	out := question{text: text, typ: "rating"}
	for i, l := range labels {
		var es []string
		if effs[i][0] != "" {
			for _, c := range codes {
				sign := effs[i][0]
				if c[0] == '-' {
					c, sign = c[1:], flip[sign]
				}
				es = append(es, c+sign+effs[i][1])
			}
		}
		out.opts = append(out.opts, opt{l, es})
	}
	return out
}

